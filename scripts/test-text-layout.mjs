import assert from 'node:assert/strict';
import { getSubtitlePositionLayout, getSubtitleSafeLayout, getTextClipLineLimit, hasRenderableText, wrapTextLines } from '../src/text-layout.js';

const ctx = { measureText: value => ({ width: Array.from(value).length * 10 }) };
assert.equal(hasRenderableText('门店招牌'), true);
assert.equal(hasRenderableText('  \n  '), false, 'whitespace-only text should not create an empty subtitle clip');
assert.equal(hasRenderableText(null), false);
assert.equal(getTextClipLineLimit(346, 37, 2), 2, 'generated subtitles can be capped at two lines');
assert.equal(getTextClipLineLimit(346, 37, null), 7, 'ordinary text clips keep their height-based line capacity');
assert.equal(getTextClipLineLimit(60, 37, 2), 1, 'the physical clip height always takes precedence over the configured cap');
assert.equal(getTextClipLineLimit(346, 37, 0), 7, 'invalid caps fall back to the height-based capacity');
assert.deepEqual(wrapTextLines(ctx, '昆明特色美食探店体验', 50, 3), ['昆明特色美', '食探店体验']);
assert.deepEqual(wrapTextLines(ctx, '第一行\n第二行', 100, 3), ['第一行', '第二行']);
assert.deepEqual(wrapTextLines(ctx, '这是一段非常非常长的中文宣传文案', 50, 2), ['这是一段非', '常非常长…']);
assert.deepEqual(wrapTextLines(ctx, '第一句\n\n第二句\n', 100, 3), ['第一句', '第二句'], 'blank and trailing lines must not consume the visible subtitle line budget');
assert.deepEqual(wrapTextLines(ctx, '\n  \n', 100, 3), [], 'whitespace-only captions render no phantom lines');
assert.deepEqual(wrapTextLines(ctx, '第一句\r\n\r\n第二句', 100, 3), ['第一句', '第二句'], 'Windows line endings and blank separators are normalized');
const layout = getSubtitleSafeLayout(1080, 1920);
assert.equal(layout.x, 76);
assert.equal(layout.width, 929);
assert.equal(layout.height, 346);
assert.equal(layout.y + layout.height, 1574);
assert.ok(layout.y + layout.height <= 1920 * 0.82);
const topLayout = getSubtitlePositionLayout(1080, 1920, 'top');
assert.equal(topLayout.y, 230, 'top preset leaves a clear upper safe margin');
assert.equal(topLayout.height, layout.height);
const middleLayout = getSubtitlePositionLayout(1080, 1920, 'middle');
assert.equal(middleLayout.y, Math.round((1920 - middleLayout.height) / 2), 'middle preset vertically centers the subtitle box');
const bottomLayout = getSubtitlePositionLayout(1080, 1920, 'bottom');
assert.deepEqual(bottomLayout, layout, 'bottom remains backward-compatible with the original default layout');
const unknownLayout = getSubtitlePositionLayout(1080, 1920, 'unknown');
assert.deepEqual(unknownLayout, layout, 'unknown positions safely fall back to bottom');
console.log('Subtitle text layout tests passed.');
