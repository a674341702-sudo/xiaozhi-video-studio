import assert from 'node:assert/strict';
import { encodePcm16Wav, createTtsVoiceFile } from '../src/tts/wav-audio.js';

const samples = new Float32Array([-1, -0.5, 0, 0.5, 1]);
const wav = encodePcm16Wav(samples, 22050);
const bytes = new Uint8Array(await wav.arrayBuffer());
const view = new DataView(bytes.buffer);
const text = (start, end) => String.fromCharCode(...bytes.slice(start, end));
assert.equal(wav.type, 'audio/wav');
assert.equal(text(0, 4), 'RIFF');
assert.equal(text(8, 12), 'WAVE');
assert.equal(view.getUint16(22, true), 1);
assert.equal(view.getUint32(24, true), 22050);
assert.equal(view.getUint16(34, true), 16);
assert.equal(view.getUint32(40, true), samples.length * 2);
assert.equal(view.getInt16(44, true), -32768);
assert.equal(view.getInt16(46, true), -16384);
assert.equal(view.getInt16(50, true), 16384);
assert.equal(view.getInt16(52, true), 32767);
assert.throws(() => encodePcm16Wav([], 22050), /Float32Array/);
assert.throws(() => encodePcm16Wav(new Float32Array([1]), 7000), /sample rate/);
assert.throws(() => encodePcm16Wav(new Float32Array([NaN]), 22050), /non-finite/);
assert.throws(() => encodePcm16Wav(new Float32Array(64), 22050), /silent/);
const file = createTtsVoiceFile(samples, 22050, 1234);
assert.ok(file instanceof File);
assert.equal(file.name, 'xiaozhi-ai-voice-1234.wav');
assert.equal(file.type, 'audio/wav');
assert.equal(file.size, 54);
console.log('TTS Float32-to-WAV adapter tests passed.');
