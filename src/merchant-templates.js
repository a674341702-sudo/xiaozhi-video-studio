export function getMerchantShotPlan(industry, count = 6) {
  const source = MERCHANT_SHOT_TEMPLATES[industry] || MERCHANT_SHOT_TEMPLATES['其他门店'];
  return Array.from({ length: Math.max(1, count) }, (_, index) => {
    const item = source[index % source.length];
    return { ...item, role: item.role + (index >= source.length ? '（补充镜头）' : '') };
  });
}
